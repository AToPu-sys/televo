#!/usr/bin/env bash
# Televo's own TURN relay (coturn) on a fresh Ubuntu 22.04/24.04 server —
# written for an Oracle Cloud "Always Free" VM (10 TB/month of traffic free),
# works on any Ubuntu VM with a public IP.
#
# Usage, as root (or paste into the VM's cloud-init "user data" field with
# the two variables filled in at the top):
#
#   TURN_SECRET=<shared secret> [TURN_DOMAIN=turn.example.com] bash setup-coturn.sh
#
# TURN_SECRET must equal the COTURN_SECRET secret of the turn-credentials
# Edge Function: the function signs short-lived credentials with it
# (coturn's "TURN REST API" scheme), so no password is ever stored in the
# app. Never commit a real secret into this file — the repository is public.
#
# TURN_DOMAIN is optional. Without it the relay uses <ip-with-dashes>.sslip.io,
# a public wildcard DNS name that always resolves to that IP, so TLS on 443
# works without touching any DNS settings.
#
# Ports to open in the cloud firewall (Oracle: VCN -> Security List ->
# Ingress Rules): UDP 3478, TCP 3478, TCP 443, TCP 80 (certificate renewal),
# UDP 49152-65535 (relayed media).
set -euo pipefail

TURN_SECRET="${TURN_SECRET:-}"
TURN_DOMAIN="${TURN_DOMAIN:-}"

if [[ -z "$TURN_SECRET" ]]; then
  echo "TURN_SECRET is required" >&2
  exit 1
fi

export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y coturn certbot curl iptables-persistent

PUBLIC_IP="$(curl -fsS4 https://api.ipify.org || curl -fsS4 https://ifconfig.me)"
PRIVATE_IP="$(hostname -I | awk '{print $1}')"
if [[ -z "$TURN_DOMAIN" ]]; then
  TURN_DOMAIN="${PUBLIC_IP//./-}.sslip.io"
fi

# Oracle's Ubuntu images ship an iptables policy that rejects everything but
# SSH; open the TURN ports in front of that REJECT rule and keep them.
for rule in \
  "-p udp --dport 3478" \
  "-p tcp --dport 3478" \
  "-p tcp --dport 443" \
  "-p tcp --dport 80" \
  "-p udp --dport 49152:65535"; do
  # shellcheck disable=SC2086
  iptables -C INPUT $rule -j ACCEPT 2>/dev/null || iptables -I INPUT 1 $rule -j ACCEPT
done
netfilter-persistent save

# Certificate for TURN over TLS on 443 (what gets through networks that only
# allow HTTPS). certbot answers the challenge on port 80 itself. Without a
# certificate the relay still runs on 3478 — just without the 443 path.
TLS_CONF=""
if certbot certonly --standalone --non-interactive --agree-tos \
  --register-unsafely-without-email -d "$TURN_DOMAIN"; then
  TLS_CONF="tls-listening-port=443
cert=/etc/coturn/certs/fullchain.pem
pkey=/etc/coturn/certs/privkey.pem
no-tlsv1
no-tlsv1_1"
else
  echo "WARNING: no certificate for $TURN_DOMAIN — TLS on 443 disabled, 3478 only." >&2
fi

install -d -o turnserver -g turnserver -m 750 /etc/coturn/certs
if [[ -n "$TLS_CONF" ]]; then
cat > /etc/letsencrypt/renewal-hooks/deploy/coturn.sh <<HOOK
#!/bin/sh
install -o turnserver -g turnserver -m 640 /etc/letsencrypt/live/$TURN_DOMAIN/fullchain.pem /etc/coturn/certs/fullchain.pem
install -o turnserver -g turnserver -m 640 /etc/letsencrypt/live/$TURN_DOMAIN/privkey.pem /etc/coturn/certs/privkey.pem
systemctl restart coturn
HOOK
chmod 755 /etc/letsencrypt/renewal-hooks/deploy/coturn.sh
install -o turnserver -g turnserver -m 640 "/etc/letsencrypt/live/$TURN_DOMAIN/fullchain.pem" /etc/coturn/certs/fullchain.pem
install -o turnserver -g turnserver -m 640 "/etc/letsencrypt/live/$TURN_DOMAIN/privkey.pem" /etc/coturn/certs/privkey.pem
fi

cat > /etc/turnserver.conf <<CONF
# Televo TURN relay — generated by scripts/turn/setup-coturn.sh
listening-port=3478
listening-ip=$PRIVATE_IP
relay-ip=$PRIVATE_IP
# Behind cloud NAT: tell clients the public address.
external-ip=$PUBLIC_IP/$PRIVATE_IP
min-port=49152
max-port=65535

realm=$TURN_DOMAIN
server-name=$TURN_DOMAIN
use-auth-secret
static-auth-secret=$TURN_SECRET
fingerprint

$TLS_CONF

# A relay for calls, nothing else: no relaying into private networks, the
# loopback, or the cloud metadata service (169.254.169.254).
no-multicast-peers
denied-peer-ip=0.0.0.0-0.255.255.255
denied-peer-ip=10.0.0.0-10.255.255.255
denied-peer-ip=100.64.0.0-100.127.255.255
denied-peer-ip=127.0.0.0-127.255.255.255
denied-peer-ip=169.254.0.0-169.254.255.255
denied-peer-ip=172.16.0.0-172.31.255.255
denied-peer-ip=192.168.0.0-192.168.255.255
denied-peer-ip=::1
denied-peer-ip=fc00::-fdff:ffff:ffff:ffff:ffff:ffff:ffff:ffff
denied-peer-ip=fe80::-febf:ffff:ffff:ffff:ffff:ffff:ffff:ffff

# One user can't take the whole box: 30 simultaneous allocations each.
user-quota=30
stale-nonce=600
no-cli
log-file=syslog
simple-log
CONF

# coturn runs as an unprivileged user; 443 needs the bind capability.
mkdir -p /etc/systemd/system/coturn.service.d
cat > /etc/systemd/system/coturn.service.d/override.conf <<UNIT
[Service]
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
LimitNOFILE=65536
UNIT

sed -i 's/^#\?TURNSERVER_ENABLED=.*/TURNSERVER_ENABLED=1/' /etc/default/coturn 2>/dev/null || true
systemctl daemon-reload
systemctl enable coturn
systemctl restart coturn

echo "TURN relay ready: $TURN_DOMAIN (public $PUBLIC_IP)"
echo "Set COTURN_HOSTS=$TURN_DOMAIN in the turn-credentials function's secrets."
