-- In-app AI assistant: a reserved system user with a fixed, well-known id,
-- auto-created as a direct conversation for every new user via the existing
-- handle_new_user trigger. Replies are generated server-side by an Edge
-- Function reacting to INSERTs into that conversation -- the client never
-- calls the Claude API or holds an API key.

-- Fixed, well-known id so the Edge Function and client code can both refer to
-- it without a lookup.
do $$
begin
  if not exists (select 1 from auth.users where id = '00000000-0000-0000-0000-000000000001') then
    insert into auth.users (id, email, encrypted_password, email_confirmed_at, created_at, updated_at, raw_app_meta_data, raw_user_meta_data, aud, role)
    values (
      '00000000-0000-0000-0000-000000000001',
      'assistant@televo.internal',
      -- Not a real password -- this account never signs in via password auth,
      -- only ever sends messages via the service-role key from the Edge Function.
      crypt(gen_random_uuid()::text, gen_salt('bf')),
      now(), now(), now(),
      '{"provider":"system","providers":["system"]}',
      '{}',
      'authenticated',
      'authenticated'
    );
  end if;
end $$;

-- handle_new_user (the trigger on auth.users) already ran for the insert
-- above and created a default profiles row ('athlete' / 'New Athlete') --
-- it fires for ANY new auth.users row, system account or not. Overwrite
-- those placeholder values rather than inserting a fresh row.
update public.profiles
set username = 'televo_assistant',
    display_name = 'Televo Assistant',
    bio = 'Ask me anything. Replies are generated by Claude.'
where id = '00000000-0000-0000-0000-000000000001';

-- Every new user gets a direct conversation with the assistant automatically.
create or replace function public.create_assistant_conversation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  conversation_id uuid;
begin
  insert into public.conversations (id, kind, created_by)
  values (gen_random_uuid(), 'direct', new.id)
  returning id into conversation_id;

  insert into public.conversation_participants (conversation_id, user_id)
  values
    (conversation_id, new.id),
    (conversation_id, '00000000-0000-0000-0000-000000000001');

  insert into public.messages (conversation_id, sender_id, kind, body)
  values (
    conversation_id,
    '00000000-0000-0000-0000-000000000001',
    'text',
    'Hi! I''m the Televo Assistant, powered by Claude. Ask me anything.'
  );

  return new;
end;
$$;

create trigger on_profile_created_add_assistant
  after insert on public.profiles
  for each row execute function public.create_assistant_conversation();

revoke execute on function public.create_assistant_conversation() from anon, public, authenticated;
